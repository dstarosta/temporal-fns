import { getWeekYearValue, type LocalWeekOptions } from './helpers/local-week.js';
import { type DateLike } from './types.js';

/**
 * The {@link getWeekYear} function options.
 */
export type GetWeekYearOptions = LocalWeekOptions;

/**
 * @summary Get the local week-numbering year of the given date.
 *
 * @description
 * Get the local week-numbering year of the given date.
 * The exact calculation depends on the values of
 * `options.weekStartsOn` (which is the index of the first day of the week)
 * and `options.firstWeekContainsDate` (which is the day of January, which is always in
 * the first week of the week-numbering year)
 *
 * Week numbering: https://en.wikipedia.org/wiki/Week#The_ISO_week_date_system
 *
 * @param date - The given date
 * @param options - An object with options
 *
 * @returns The local week-numbering year
 *
 * @example
 * // Which week numbering year is 26 December 2004 with the default settings?
 * const result = getWeekYear(new Date(2004, 11, 26))
 * //=> 2005
 *
 * @example
 * // Which week numbering year is 26 December 2004 if week starts on Saturday?
 * const result = getWeekYear(new Date(2004, 11, 26), { weekStartsOn: 6 })
 * //=> 2004
 *
 * @example
 * // Which week numbering year is 26 December 2004 if the first week contains 4 January?
 * const result = getWeekYear(new Date(2004, 11, 26), { firstWeekContainsDate: 4 })
 * //=> 2004
 */
export function getWeekYear(date: Date, options?: GetWeekYearOptions): number;
export function getWeekYear(date: DateLike, options?: GetWeekYearOptions): number;
export function getWeekYear(date: Date | DateLike, options?: GetWeekYearOptions): number {
  return getWeekYearValue(date, options);
}
